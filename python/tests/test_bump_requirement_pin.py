"""Tests for scripts/bump_requirement_pin.py."""

from __future__ import annotations

import importlib.util
import io
import json
import sys
import urllib.error
from email.message import Message
from pathlib import Path

import pytest

SCRIPT = Path(__file__).parent.parent / "scripts" / "bump_requirement_pin.py"


def _load_script():
    spec = importlib.util.spec_from_file_location("bump_requirement_pin", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves annotations through sys.modules.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


bump = _load_script()

OLD_A = "a" * 64
OLD_B = "b" * 64
NEW_C = "c" * 64
NEW_D = "d" * 64
NEW_E = "e" * 64

LOCKFILE = f"""\
# This file was autogenerated
packaging==25.0 \\
    --hash=sha256:{"1" * 64}
    # via pytest
pillow==12.3.0 \\
    --hash=sha256:{OLD_A} \\
    --hash=sha256:{OLD_B}
    # via
    #   -r dev.in
    #   pikepdf
pluggy==1.6.0 \\
    --hash=sha256:{"2" * 64}
    # via pytest
"""

SPLIT_LOCKFILE = f"""\
pillow==12.3.0 ; python_version < "3.11" \\
    --hash=sha256:{OLD_A}
    # via pikepdf
pillow==13.0.0 ; python_version >= "3.11" \\
    --hash=sha256:{OLD_B}
    # via pikepdf
"""


def test_replaces_the_version_and_every_hash():
    text, old_version = bump.replace_pin(LOCKFILE, "pillow", "13.0.0", [NEW_C, NEW_D, NEW_E])

    assert old_version == "12.3.0"
    expected_block = (
        "pillow==13.0.0 \\\n"
        f"    --hash=sha256:{NEW_C} \\\n"
        f"    --hash=sha256:{NEW_D} \\\n"
        f"    --hash=sha256:{NEW_E}\n"
        "    # via\n"
        "    #   -r dev.in\n"
        "    #   pikepdf\n"
    )
    assert expected_block in text
    assert OLD_A not in text
    assert OLD_B not in text


def test_leaves_every_other_line_alone():
    text, _ = bump.replace_pin(LOCKFILE, "pillow", "13.0.0", [NEW_C])

    before, _, after = LOCKFILE.partition("pillow==12.3.0")
    assert text.startswith(before)
    assert text.endswith(after[after.index("pluggy==") :])


def test_a_single_hash_ends_without_a_continuation():
    text, _ = bump.replace_pin(LOCKFILE, "pillow", "13.0.0", [NEW_C])

    assert f"pillow==13.0.0 \\\n    --hash=sha256:{NEW_C}\n    # via\n" in text


def test_the_name_is_matched_the_way_pip_matches_it():
    text, _ = bump.replace_pin(LOCKFILE, "Pillow", "13.0.0", [NEW_C])

    assert "pillow==13.0.0 \\" in text


def test_extras_stay_on_the_requirement():
    lockfile = f"coverage[toml]==7.13.4 \\\n    --hash=sha256:{OLD_A}\n    # via pytest-cov\n"

    text, old_version = bump.replace_pin(lockfile, "coverage", "7.14.0", [NEW_C])

    assert old_version == "7.13.4"
    assert text == f"coverage[toml]==7.14.0 \\\n    --hash=sha256:{NEW_C}\n    # via pytest-cov\n"


def test_a_split_keeps_the_old_pin_under_its_marker():
    split = bump.Split(keep_old_when='python_version < "3.11"', new_when='python_version >= "3.11"')

    text, _ = bump.replace_pin(LOCKFILE, "pillow", "13.0.0", [NEW_C], split=split)

    expected = (
        'pillow==12.3.0 ; python_version < "3.11" \\\n'
        f"    --hash=sha256:{OLD_A} \\\n"
        f"    --hash=sha256:{OLD_B}\n"
        "    # via\n"
        "    #   -r dev.in\n"
        "    #   pikepdf\n"
        'pillow==13.0.0 ; python_version >= "3.11" \\\n'
        f"    --hash=sha256:{NEW_C}\n"
        "    # via\n"
        "    #   -r dev.in\n"
        "    #   pikepdf\n"
        "pluggy==1.6.0 \\\n"
    )
    assert expected in text


def test_two_blocks_need_the_marker_of_the_one_to_bump():
    with pytest.raises(bump.PinError, match="--only-marker"):
        bump.replace_pin(SPLIT_LOCKFILE, "pillow", "13.0.1", [NEW_C])


def test_the_named_block_is_bumped_and_keeps_its_marker():
    text, old_version = bump.replace_pin(
        SPLIT_LOCKFILE, "pillow", "13.0.1", [NEW_C], only_marker='python_version >= "3.11"'
    )

    assert old_version == "13.0.0"
    assert f'pillow==13.0.1 ; python_version >= "3.11" \\\n    --hash=sha256:{NEW_C}\n' in text
    assert f'pillow==12.3.0 ; python_version < "3.11" \\\n    --hash=sha256:{OLD_A}\n' in text


def test_a_block_with_a_marker_cannot_be_split_again():
    split = bump.Split(keep_old_when='python_version < "3.12"', new_when='python_version >= "3.12"')

    with pytest.raises(bump.PinError, match="cannot be split again"):
        bump.replace_pin(
            SPLIT_LOCKFILE,
            "pillow",
            "14.0.0",
            [NEW_C],
            only_marker='python_version >= "3.11"',
            split=split,
        )


def test_a_package_that_is_not_pinned_is_an_error():
    with pytest.raises(bump.PinError, match="No pinned block for certifi"):
        bump.replace_pin(LOCKFILE, "certifi", "2026.10.18", [NEW_C])


def test_an_unknown_marker_is_an_error():
    with pytest.raises(bump.PinError, match="carries the marker"):
        bump.replace_pin(SPLIT_LOCKFILE, "pillow", "13.0.1", [NEW_C], only_marker="os_name == 'nt'")


def test_a_release_without_hashes_is_refused():
    with pytest.raises(bump.PinError, match="No hashes"):
        bump.replace_pin(LOCKFILE, "pillow", "13.0.0", [])


def test_a_release_pypi_does_not_have_is_reported_by_name(monkeypatch):
    def not_found(url, timeout):
        raise urllib.error.HTTPError(url, 404, "Not Found", Message(), None)

    monkeypatch.setattr(bump.urllib.request, "urlopen", not_found)

    with pytest.raises(bump.PinError, match=r"PyPI has no release pillow 99\.0\.0"):
        bump.fetch_sha256_digests("pillow", "99.0.0")


def test_an_unreachable_pypi_is_reported(monkeypatch):
    def unreachable(url, timeout):
        raise urllib.error.URLError("connection refused")

    monkeypatch.setattr(bump.urllib.request, "urlopen", unreachable)

    with pytest.raises(bump.PinError, match="Could not reach PyPI: connection refused"):
        bump.fetch_sha256_digests("pillow", "13.0.0")


def test_digests_come_back_sorted_from_the_release_listing(monkeypatch):
    listing = {"urls": [{"digests": {"sha256": NEW_D}}, {"digests": {"sha256": NEW_C}}]}
    asked = []

    def respond(url, timeout):
        asked.append(url)
        return io.BytesIO(json.dumps(listing).encode())

    monkeypatch.setattr(bump.urllib.request, "urlopen", respond)

    assert bump.fetch_sha256_digests("pillow", "13.0.0") == [NEW_C, NEW_D]
    assert asked == ["https://pypi.org/pypi/pillow/13.0.0/json"]


def test_main_rewrites_every_lockfile(tmp_path, capsys):
    first = tmp_path / "dev.txt"
    second = tmp_path / "build.txt"
    first.write_text(LOCKFILE, encoding="utf-8")
    second.write_text(LOCKFILE, encoding="utf-8")
    requested = []

    def fake_fetch(package, version):
        requested.append((package, version))
        return [NEW_C]

    code = bump.main(["pillow", "13.0.0", str(first), str(second)], fetch_digests=fake_fetch)

    assert code == 0
    assert requested == [("pillow", "13.0.0")]
    for lockfile in (first, second):
        assert "pillow==13.0.0 \\" in lockfile.read_text(encoding="utf-8")
    assert "dev.txt: pillow 12.3.0 -> 13.0.0" in capsys.readouterr().out


def test_main_writes_nothing_when_one_lockfile_cannot_be_bumped(tmp_path, capsys):
    good = tmp_path / "dev.txt"
    bad = tmp_path / "audit.txt"
    good.write_text(LOCKFILE, encoding="utf-8")
    bad.write_text("certifi==2026.6.17 \\\n    --hash=sha256:" + OLD_A + "\n", encoding="utf-8")

    code = bump.main(["pillow", "13.0.0", str(good), str(bad)], fetch_digests=lambda *_: [NEW_C])

    assert code == 1
    assert good.read_text(encoding="utf-8") == LOCKFILE
    assert "No pinned block for pillow" in capsys.readouterr().err


@pytest.mark.parametrize(
    "argv",
    [
        ["pillow", "13.0.0", "dev.txt", "--keep-old-when", "x"],
        ["pillow/../x", "13.0.0", "dev.txt"],
        ["pillow", "13.0.0?x=1", "dev.txt"],
        [
            "pillow",
            "13.0.0",
            "dev.txt",
            "--only-marker",
            "m",
            "--keep-old-when",
            "a",
            "--new-when",
            "b",
        ],
    ],
)
def test_main_refuses_bad_arguments_before_asking_pypi(argv):
    def must_not_fetch(package, version):
        raise AssertionError("PyPI was asked")

    with pytest.raises(SystemExit) as excinfo:
        bump.main(argv, fetch_digests=must_not_fetch)

    assert excinfo.value.code == 2


def test_the_real_lockfiles_are_in_the_shape_the_tool_reads():
    """Every pinned block in the repository's lockfiles must be one the tool finds."""
    requirements = Path(__file__).parent.parent.parent / ".github" / "requirements"
    lockfiles = sorted(requirements.glob("*.txt"))
    assert lockfiles

    for lockfile in lockfiles:
        text = lockfile.read_text(encoding="utf-8")
        pinned_lines = [line for line in text.splitlines() if "==" in line and line[:1].isalnum()]
        found = list(bump._BLOCK.finditer(text))
        assert len(found) == len(pinned_lines), lockfile.name
